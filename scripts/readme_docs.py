"""Writes README*.md and HOW_TO_INSTALL*.md in every UI language from `i18n/docs/`.

Each doc has one template, `i18n/docs/<DOC>.md`, which holds what is the same in every language
(tables, commands, links, file names), and every language has its strings in
`i18n/docs/{locale}.json`. A `{{key}}` in a template is that string; `{{languages}}` is the list of
the other languages and `{{notice}}` the notice of a machine-made language (brief §8). A string
may name per-language targets: `{help}`, `{about}`, `{install}`, `{run}` (the README's Run
section), `{fix}` (the Translation fix form for that language) and `{count}` (how many languages).
Like the UI, a language without a key shows the `en-US` text. Run it after changing a template
or a string; a test fails while the files are out of date.

    uv run python scripts/readme_docs.py
"""

import json
import re
import sys
import unicodedata
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
from app.locales import DEFAULT_LOCALE  # noqa: E402  (after the path to the repository)
from scripts.help_docs import FIX_URL, LOCALES, _strings, doc_path, unreviewed_notice  # noqa: E402

SOURCE = ROOT / "i18n" / "docs"
DOCS = ("README", "HOW_TO_INSTALL")
TEMPLATE_KEY = re.compile(r"\{\{([\w.]+)\}\}")
TOKEN = re.compile(r"\{(help|about|install|run|fix|count)\}")


def path_of(doc: str, locale: str) -> Path:
    """Where one language's doc is written, at the repository's root.

    Args:
        doc (str): `README` or `HOW_TO_INSTALL`.
        locale (str): The language.

    Returns:
        Path: `<DOC>.md` for English, `<DOC>.<locale>.md` for the others.
    """
    return ROOT / (f"{doc}.md" if locale == DEFAULT_LOCALE else f"{doc}.{locale}.md")


def strings(locale: str) -> dict[str, str]:
    """One language's doc strings, with English for the keys it lacks.

    Args:
        locale (str): The language.

    Returns:
        dict[str, str]: Key -> text.
    """
    english = json.loads((SOURCE / f"{DEFAULT_LOCALE}.json").read_text(encoding="utf-8"))
    path = SOURCE / f"{locale}.json"
    own = json.loads(path.read_text(encoding="utf-8")) if path.is_file() else {}
    return {**english, **own}


def anchor(heading: str) -> str:
    """The anchor GitHub gives a heading.

    Args:
        heading (str): The heading's text.

    Returns:
        str: Lowercase, with hyphens for spaces, keeping only letters (with their combining
            marks, as in Devanagari), digits, `_` and `-`.
    """
    kept = (
        char
        for char in heading.strip().lower()
        if char in " -" or unicodedata.category(char)[0] in "LMN" or char == "_"
    )
    return "".join(kept).replace(" ", "-")


def _fill(text: str, locale: str, texts: dict[str, str]) -> str:
    """Puts a language's targets into one of its strings.

    Args:
        text (str): The string.
        locale (str): The language.
        texts (dict[str, str]): The language's strings, for the Run heading.

    Returns:
        str: The string with its `{tokens}` replaced.
    """
    targets = {
        "help": doc_path(locale, "HELP").relative_to(ROOT).as_posix(),
        "about": doc_path(locale, "ABOUT").relative_to(ROOT).as_posix(),
        "install": path_of("HOW_TO_INSTALL", locale).name,
        "run": f"{path_of('README', locale).name}#{anchor(texts['readme.run.title'])}",
        "fix": f"{FIX_URL}&language={locale}",
        "count": str(len(LOCALES)),
    }
    return TOKEN.sub(lambda match: targets[match.group(1)], text)


def _languages(doc: str, locale: str) -> str:
    """The links to the same doc in the other languages, each named in its own language.

    Args:
        doc (str): `README` or `HOW_TO_INSTALL`.
        locale (str): The language of the doc being written.

    Returns:
        str: The links, separated by dots.
    """
    return " · ".join(
        f"[{_strings(code)['locale.name']}]({path_of(doc, code).name})"
        for code in LOCALES
        if code != locale
    )


def render(doc: str, locale: str) -> str:
    """One language's doc, as Markdown.

    Args:
        doc (str): `README` or `HOW_TO_INSTALL`.
        locale (str): The language.

    Returns:
        str: The Markdown text.
    """
    texts = strings(locale)
    template = (SOURCE / f"{doc}.md").read_text(encoding="utf-8")
    special = {
        "languages": _languages(doc, locale),
        "notice": "\n".join(unreviewed_notice(locale)).strip(),
    }

    def value(match: re.Match[str]) -> str:
        """One `{{key}}` of the template.

        Args:
            match (re.Match[str]): The placeholder.

        Returns:
            str: Its text.
        """
        key = match.group(1)
        return special[key] if key in special else _fill(texts[key], locale, texts)

    text = TEMPLATE_KEY.sub(value, template)
    text = re.sub(r"\n{3,}", "\n\n", text)
    header = "<!-- Generated by scripts/readme_docs.py from i18n/docs/. Do not edit. -->\n\n"
    return header + text.rstrip("\n") + "\n"


def main() -> None:
    """Writes every doc in every language."""
    for doc in DOCS:
        for locale in LOCALES:
            path = path_of(doc, locale)
            path.write_text(render(doc, locale), encoding="utf-8")
            print(path.relative_to(ROOT))


if __name__ == "__main__":
    main()
