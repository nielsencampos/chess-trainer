"""Writes a Vale style per glossary, so the UI and the docs cannot bring back an avoided word.

Each `i18n/glossary/{locale}.toml` becomes `.vale/styles/Glossary{Name}/Avoid.yml`, a
substitution rule that flags every word in a term's `avoid` list and suggests the term's
translation (`pt-BR` → `GlossaryPtBR`). The locale's `vale` styles in `i18n/locales.toml` and its
docs section in `.vale.ini` list that style. Run it after changing a glossary; a test fails while
the files are out of date.

    uv run python scripts/vale_glossary.py
"""

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
from catalog.translations import GLOSSARY_DIR, load_glossary  # noqa: E402  (after the path)

STYLES = ROOT / ".vale" / "styles"
# Characters with a meaning in Vale's (Go) regular expressions; a space or hyphen has none.
SPECIAL = re.compile(r"([\\.^$|?*+()\[\]{}])")


def style_name(locale: str) -> str:
    """Names the Vale style of a locale's glossary.

    Args:
        locale (str): A locale code, such as `pt-BR`.

    Returns:
        str: The style's name, such as `GlossaryPtBR`.
    """
    return "Glossary" + "".join(part[:1].upper() + part[1:] for part in locale.split("-"))


def _quote(text: str) -> str:
    """Quotes a text for YAML, in single quotes.

    Args:
        text (str): The text.

    Returns:
        str: The quoted text.
    """
    return "'" + text.replace("'", "''") + "'"


def rule(path: Path) -> str | None:
    """Builds the substitution rule of one glossary.

    Args:
        path (Path): An `i18n/glossary/{locale}.toml` file.

    Returns:
        str | None: The rule's YAML, or None when no term has words to avoid.
    """
    swaps = [
        (word, term.translation) for term in load_glossary(path).values() for word in term.avoid
    ]
    if not swaps:
        return None
    lines = [
        f"# Generated by scripts/vale_glossary.py from i18n/glossary/{path.name}; do not edit.",
        "# Each word a glossary term avoids, and the term to use instead (brief §8).",
        "extends: substitution",
        "message: \"Use '%s' (the glossary's term), not '%s'.\"",
        "level: error",
        "ignorecase: true",
        "swap:",
    ]
    lines += [f"  {_quote(SPECIAL.sub(r'\\\1', word))}: {_quote(use)}" for word, use in swaps]
    return "\n".join(lines) + "\n"


def expected(directory: Path = GLOSSARY_DIR) -> dict[Path, str]:
    """Lists the style files the glossaries give.

    Args:
        directory (Path): The `i18n/glossary` folder.

    Returns:
        dict[Path, str]: Each rule file and its text.
    """
    files: dict[Path, str] = {}
    for path in sorted(directory.glob("*.toml")):
        if (text := rule(path)) is not None:
            files[STYLES / style_name(path.stem) / "Avoid.yml"] = text
    return files


def main() -> int:
    """Writes every glossary's style and removes the styles of glossaries that are gone.

    Returns:
        int: The exit code, 0.
    """
    files = expected()
    for old in STYLES.glob("Glossary*/Avoid.yml"):
        if old not in files:
            old.unlink()
            old.parent.rmdir()
    for path, text in files.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")
        print(path.relative_to(ROOT))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
