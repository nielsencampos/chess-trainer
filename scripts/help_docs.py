"""Writes docs/HELP*.md from the app's Help page, so the repository and the app say the same.

The text comes from the Help page's i18n keys (`web/index.html`, `#help-page`) in each language
of `web/i18n`, and the pictures from `web/help` (see `scripts/help_media.py`). Run it after
changing the Help page or its strings; a test fails while the files are out of date.

    uv run python scripts/help_docs.py
"""

import json
from html.parser import HTMLParser
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
WEB = ROOT / "web"
DOCS = ROOT / "docs"
LOCALES = ["en", "pt-BR", "es"]  # English first: it is docs/HELP.md.


class _HelpOutline(HTMLParser):
    """Reads the Help page's structure from index.html as a list of blocks.

    Each block is `(kind, key)`: kind is `title`, `para`, `notice-title`, `notice-text`,
    `section`, `item` or `figure` (whose key is the picture's name).
    """

    def __init__(self) -> None:
        """Starts outside the Help page."""
        super().__init__()
        self.depth = 0
        self.blocks: list[tuple[str, str]] = []
        self.in_notice = False

    def handle_starttag(self, tag: str, attrs: list[tuple[str, str | None]]) -> None:
        """Records the i18n key of each element of the Help page.

        Args:
            tag (str): The element's tag.
            attrs (list[tuple[str, str | None]]): Its attributes.
        """
        values = dict(attrs)
        if values.get("id") == "help-page":
            self.depth = 1
            return
        if not self.depth:
            return
        if tag == "section":
            self.depth += 1
        if tag == "div" and "notice" in (values.get("class") or ""):
            self.in_notice = True
        key = values.get("data-i18n")
        if tag == "img" and values.get("data-help-img"):
            self.blocks.append(("figure", values["data-help-img"] or ""))
        elif key and tag == "h2":
            self.blocks.append(("title", key))
        elif key and tag == "strong" and self.in_notice:
            self.blocks.append(("notice-title", key))
        elif key and tag == "p":
            self.blocks.append(("notice-text" if self.in_notice else "para", key))
        elif key and tag == "summary":
            self.blocks.append(("section", key))
        elif key and tag == "li":
            self.blocks.append(("item", key))

    def handle_endtag(self, tag: str) -> None:
        """Leaves a notice, or the Help page at its closing section.

        Args:
            tag (str): The element's tag.
        """
        if not self.depth:
            return
        if tag == "div":
            self.in_notice = False
        if tag == "section":
            self.depth -= 1


def outline() -> list[tuple[str, str]]:
    """The Help page's blocks, in order.

    Returns:
        list[tuple[str, str]]: `(kind, key)` pairs.
    """
    parser = _HelpOutline()
    parser.feed((WEB / "index.html").read_text(encoding="utf-8"))
    return parser.blocks


def doc_path(locale: str) -> Path:
    """Where one language's guide is written.

    Args:
        locale (str): The language.

    Returns:
        Path: `docs/HELP.md` for English, `docs/HELP.<locale>.md` for the others.
    """
    return DOCS / ("HELP.md" if locale == "en" else f"HELP.{locale}.md")


def render(locale: str) -> str:
    """One language's guide, as Markdown.

    Args:
        locale (str): The language.

    Returns:
        str: The Markdown text.
    """
    english = json.loads((WEB / "i18n" / "en.json").read_text(encoding="utf-8"))
    own = json.loads((WEB / "i18n" / f"{locale}.json").read_text(encoding="utf-8"))
    strings = {**english, **own}
    names = {
        code: json.loads((WEB / "i18n" / f"{code}.json").read_text(encoding="utf-8"))["locale.name"]
        for code in LOCALES
    }
    others = " · ".join(
        f"[{names[code]}]({doc_path(code).name})" for code in LOCALES if code != locale
    )
    lines = [
        "<!-- Generated by scripts/help_docs.py from the app's Help page. Do not edit. -->",
        "",
    ]
    for kind, key in outline():
        if kind == "title":
            lines += [f"# {strings[key]}", "", others, ""]
        elif kind == "para":
            lines += [strings[key], ""]
        elif kind == "notice-title":
            lines += [f"> **{strings[key]}**", ">"]
        elif kind == "notice-text":
            lines += [f"> {strings[key]}", ""]
        elif kind == "section":
            lines += ["", f"## {strings[key]}", ""]
        elif kind == "item":
            lines += [f"- {strings[key]}"]
        elif kind == "figure":
            picture = WEB / "help" / locale / f"{key}.webp"
            if not picture.is_file():
                picture = WEB / "help" / "en" / f"{key}.webp"
            caption = strings[f"help.fig.{key}"]
            relative = picture.relative_to(ROOT).as_posix()
            lines += ["", f"![{caption}](../{relative})", "", f"*{caption}*", ""]
    text = "\n".join(lines)
    while "\n\n\n" in text:
        text = text.replace("\n\n\n", "\n\n")
    return text.rstrip("\n") + "\n"


def main() -> None:
    """Writes the guide of every language."""
    for locale in LOCALES:
        path = doc_path(locale)
        path.write_text(render(locale), encoding="utf-8")
        print(path.relative_to(ROOT))


if __name__ == "__main__":
    main()
